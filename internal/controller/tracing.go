package controller

import (
	"go.opentelemetry.io/otel"
	"go.opentelemetry.io/otel/codes"
	"go.opentelemetry.io/otel/trace"
)

// tracer makes the controller's spans (ARCHITECTURE.md §7.1): exec,
// lease.acquire, replay, harness.turn, model.call, tool.execute, recovery.
var tracer = otel.Tracer("conductor.controller")

func endSpan(span trace.Span, err error) {
	if err != nil {
		span.RecordError(err)
		span.SetStatus(codes.Error, err.Error())
	}
	span.End()
}
